#!/usr/bin/env python3
"""Generate HeadlineSeqV4/Defs.lean from HeadlineSeqV4/Challenge.lean (geoseq V4 stage V9-H).

The Palomar Challenge must import only Mathlib, so it holds its own definitions; the Solution side needs the
same constants. This script copies the block between `-- BEGIN DEFINITIONS` and `-- END DEFINITIONS` of the
Challenge verbatim into `HeadlineSeqV4/Defs.lean` (same namespace and `open`s). Comparator on
comparatorHeadlineSeqV4.json checks that the constants agree. Usage: uv run scripts/gen_headline_seq_v4_defs.py
"""
import os
L = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(L, 'HeadlineSeqV4', 'Challenge.lean')).read()
body = src.split('-- BEGIN DEFINITIONS\n', 1)[1].split('-- END DEFINITIONS\n', 1)[0]
header = '''/-
Copyright (c) 2026 Leonhard Gruenschloss. Released under the MIT license.
Author: Leonhard Gruenschloss.
GENERATED by scripts/gen_headline_seq_v4_defs.py from HeadlineSeqV4/Challenge.lean -- do not edit by hand.
The definitions of the geoseq V4 headline entry (verbatim copy of the Challenge's definitions block), for
the Solution side (HeadlineSeqV4/Solution.lean).
-/
module
public import Mathlib

@[expose] public section

namespace GeoSeqV4

open Finset

'''
open(os.path.join(L, 'HeadlineSeqV4', 'Defs.lean'), 'w').write(header + body + '\nend GeoSeqV4\n')
print('wrote HeadlineSeqV4/Defs.lean')
